# Задание 10 (Даны два списка одинаковой длины: страны и их столицы. Составьте из них словарь и выведите столицу страны, которую введёт пользователь)
countries = ["Россия", "Франция", "Италия"]
capitals = ["Москва", "Париж", "Рим"]
country_dict = dict(zip(countries, capitals))
country = input("Введите страну: ")
print(country_dict[country])
